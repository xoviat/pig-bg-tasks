//! End-to-end proof that a **Go** client receives this link's task
//! busy-state notifications: the Rust link server accepts a real Go
//! process's `op:"watch-tasks"` subscription over its AF_UNIX socket, the
//! task registry flips the state (a task starts, then the same task
//! stops), and the Go side must print both `task-busy` events before the
//! link's shutdown closes its connection.
//!
//! The Go source is carried here as a string and written to
//! `<repo>/pig-tmp/linkwatch/` (gitignored) at run time — **no `.go` file
//! is ever committed** (maintainer directive). The test skips when `go` is
//! not installed.

use std::io::{BufRead, BufReader, Read};
use std::process::{Child, Command, Stdio};
use std::sync::mpsc;
use std::sync::{Arc, Mutex};
use std::time::{Duration, Instant};

use pig_bg_tasks::bg::registry::{JobStatus, Registry};
use pig_bg_tasks::link::Policy;
use pig_bg_tasks::link::server::{self, ServerOpts};

/// The generated client: subscribe, print the ack, print every event, and
/// exit 0 the moment the link closes the connection (exit 1 on a timeout
/// or anything it did not expect).
const GO_SRC: &str = r#"// Command linkwatch subscribes to one pig-bg-tasks link session's task
// busy-state notifications and prints every frame it receives:
//
//	SUBSCRIBED busy=<bool>   the op:"watch-tasks" ack snapshot
//	EVENT busy=<bool>        one task-busy event per flip
//	EOF                      the link closed the connection (exit 0)
//
// TIMEOUT/ERROR lines exit 1. Generated by the Rust test
// go_client_receives_busy_notifications — never committed as a .go file.
package main

import (
	"bufio"
	"encoding/json"
	"fmt"
	"net"
	"os"
	"path/filepath"
	"time"
)

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}

func main() {
	if len(os.Args) != 2 {
		fail("usage: linkwatch <session-id>")
	}
	// The same endpoint derivation as the Rust link:
	// <os temp dir>/pig-sandbox-<safe id>.sock
	path := filepath.Join(os.TempDir(), "pig-sandbox-"+safeID(os.Args[1])+".sock")

	var conn net.Conn
	var err error
	for attempt := 0; attempt < 40; attempt++ {
		conn, err = net.Dial("unix", path)
		if err == nil {
			break
		}
		time.Sleep(250 * time.Millisecond)
	}
	if err != nil {
		fail("dial %s: %v", path, err)
	}
	defer conn.Close()

	if _, err := fmt.Fprintf(conn, "{\"v\":1,\"op\":\"watch-tasks\"}\n"); err != nil {
		fail("write: %v", err)
	}

	r := bufio.NewReader(conn)
	ack, err := r.ReadString('\n')
	if err != nil {
		fail("ack read: %v", err)
	}
	var a struct {
		OK    bool   `json:"ok"`
		Busy  bool   `json:"busy"`
		Error string `json:"error"`
	}
	if err := json.Unmarshal([]byte(ack), &a); err != nil {
		fail("ack %q: %v", ack, err)
	}
	if !a.OK {
		fail("refused: %s", a.Error)
	}
	fmt.Printf("SUBSCRIBED busy=%v\n", a.Busy)

	for {
		_ = conn.SetReadDeadline(time.Now().Add(30 * time.Second))
		line, err := r.ReadString('\n')
		if err != nil {
			if ne, ok := err.(net.Error); ok && ne.Timeout() {
				fmt.Println("TIMEOUT")
				os.Exit(1)
			}
			fmt.Println("EOF")
			os.Exit(0)
		}
		var ev struct {
			Event string `json:"event"`
			Busy  bool   `json:"busy"`
		}
		if err := json.Unmarshal([]byte(line), &ev); err != nil {
			fail("event %q: %v", line, err)
		}
		if ev.Event != "task-busy" {
			fail("unexpected event %q", ev.Event)
		}
		fmt.Printf("EVENT busy=%v\n", ev.Busy)
	}
}

// safeID mirrors the Rust link's safe_id: only [0-9A-Za-z_-] survive.
func safeID(s string) string {
	out := make([]rune, 0, len(s))
	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9', r == '-', r == '_':
			out = append(out, r)
		default:
			out = append(out, '-')
		}
	}
	if len(out) == 0 {
		out = append(out, '-')
	}
	return string(out)
}
"#;

/// Where the generated Go client lives (repo `pig-tmp/`, gitignored).
fn go_dir() -> std::path::PathBuf {
    std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../pig-tmp/linkwatch")
}

/// The next line the Go client printed, with its stderr as context when
/// it says nothing at all (a compile error, a refused dial, a hang).
fn next_line(
    rx: &mpsc::Receiver<String>,
    stderr: &Arc<Mutex<String>>,
    secs: u64,
) -> String {
    match rx.recv_timeout(Duration::from_secs(secs)) {
        Ok(line) => line,
        Err(e) => panic!(
            "the Go client produced no line within {secs}s ({e}); stderr: {}",
            stderr.lock().unwrap_or_else(|e| e.into_inner())
        ),
    }
}

/// Bounded wait for the Go client's exit (it must not be left running).
fn wait_for_exit(child: &mut Child, stderr: &Arc<Mutex<String>>, secs: u64) -> std::process::ExitStatus {
    let deadline = Instant::now() + Duration::from_secs(secs);
    loop {
        match child.try_wait().expect("try_wait") {
            Some(status) => return status,
            None if Instant::now() < deadline => {
                std::thread::sleep(Duration::from_millis(50));
            }
            None => {
                let _ = child.kill();
                let _ = child.wait();
                panic!(
                    "the Go client did not exit within {secs}s; stderr: {}",
                    stderr.lock().unwrap_or_else(|e| e.into_inner())
                );
            }
        }
    }
}

/// The whole path: Go subscribes → the registry starts a task (busy) →
/// the same task stops (not busy) → the link shuts down (EOF, exit 0).
#[test]
fn go_client_receives_busy_notifications() {
    match Command::new("go").arg("version").output() {
        Ok(o) if o.status.success() => {}
        _ => {
            eprintln!("go_watch: `go` is not installed — test skipped");
            return;
        }
    }

    let dir = go_dir();
    std::fs::create_dir_all(&dir).expect("pig-tmp/linkwatch");
    std::fs::write(dir.join("main.go"), GO_SRC).expect("write main.go");
    std::fs::write(dir.join("go.mod"), "module linkwatch\n\ngo 1.21\n").expect("write go.mod");

    let session = format!("go-watch-{}", std::process::id());
    // Production wiring: busy = any task in the process registry (the same
    // closure session_start hands the link; the registry's own start/exit
    // hooks are what fire `broadcast_busy`).
    let paths = server::start(ServerOpts {
        session_id: session.clone(),
        policy: std::sync::Arc::new(|| Policy {
            mode: "workspace-write".into(),
            workspace: String::new(),
            temp: std::env::temp_dir().to_string_lossy().into_owned(),
            extras: vec![],
        }),
        approver: None,
        on_policy_update: None,
        tasks_busy: std::sync::Arc::new(|| {
            let (running, _, _) = Registry::shared().snapshot();
            !running.is_empty()
        }),
    });
    assert_eq!(paths.len(), 1, "one endpoint per session: {paths:?}");

    let mut child = Command::new("go")
        .arg("run")
        .arg(".")
        .arg(&session)
        .current_dir(&dir)
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .expect("spawn `go run`");
    let stdout = child.stdout.take().expect("stdout");
    let stderr = child.stderr.take().expect("stderr");
    let (tx, rx) = mpsc::channel::<String>();
    std::thread::spawn(move || {
        for line in BufReader::new(stdout).lines().map_while(Result::ok) {
            if tx.send(line).is_err() {
                break;
            }
        }
    });
    let errbuf = Arc::new(Mutex::new(String::new()));
    {
        let errbuf = errbuf.clone();
        std::thread::spawn(move || {
            let mut s = String::new();
            let _ = BufReader::new(stderr).read_to_string(&mut s);
            *errbuf.lock().unwrap_or_else(|e| e.into_inner()) = s;
        });
    }

    // 1. The subscription ack snapshots the (still idle) link.
    let line = next_line(&rx, &errbuf, 120); // `go run` compiles first
    assert_eq!(line, "SUBSCRIBED busy=false", "{line}");

    // 2. A task starts → the registry flips the link to busy.
    let reg = Registry::shared();
    let job = reg.new_running_job(
        "bash-gowatch",
        "sleep 1",
        None,
        "/tmp/gowatch.log",
        "tc-gowatch",
        "",
        true,
    );
    assert_eq!(next_line(&rx, &errbuf, 15), "EVENT busy=true");

    // 3. The same task stops → not busy again.
    job.mark_terminal(JobStatus::Completed, Some(0));
    reg.forget(&job);
    assert_eq!(next_line(&rx, &errbuf, 15), "EVENT busy=false");

    // 4. The link's shutdown closes the subscription: the Go client sees
    //    EOF and exits 0 (nothing else may arrive first).
    server::stop_with("go_watch_done");
    assert_eq!(next_line(&rx, &errbuf, 15), "EOF");
    let status = wait_for_exit(&mut child, &errbuf, 30);
    assert!(
        status.success(),
        "the Go client exited with {status}; stderr: {}",
        errbuf.lock().unwrap_or_else(|e| e.into_inner())
    );
}
